--
-- Add triggers to tables containing updated_at columns so
-- the timestamp is refreshed whenever a row is modified
--

CREATE OR REPLACE FUNCTION set_updated_at_fn()
    RETURNS trigger
    LANGUAGE "plpgsql"
    SET search_path = ''
AS $$
BEGIN
	NEW.updated_at = now();
	RETURN NEW;
END;
$$;
--> statement-breakpoint

CREATE OR REPLACE FUNCTION add_updated_at_triggers_fn()
    RETURNS void
    LANGUAGE "plpgsql"
    SET search_path = ''
AS $$
DECLARE
    record RECORD;
BEGIN
    FOR record IN
        SELECT DISTINCT
            table_name
        FROM
            information_schema.columns
        WHERE
            table_schema = 'public' AND
            column_name = 'updated_at'
    LOOP
        EXECUTE format(
            'CREATE OR REPLACE TRIGGER "%s_bu_trig" BEFORE UPDATE ON "public"."%s" FOR EACH ROW WHEN (OLD IS DISTINCT FROM NEW) EXECUTE FUNCTION "public".set_updated_at_fn();',
			record.table_name,
			record.table_name
        );
    END LOOP;
END;
$$;
--> statement-breakpoint

