--
-- Make foreign key constraints deferrable
--

CREATE OR REPLACE FUNCTION set_deferrable_fk_constraints_fn()
    RETURNS void
    LANGUAGE "plpgsql"
    SET search_path = ''
AS $$
DECLARE
    record RECORD;
BEGIN
    FOR record IN
        SELECT
            conname,
            conrelid::regclass AS table_name
        FROM
            pg_constraint
        WHERE
            contype = 'f' AND
            connamespace = 'public'::regnamespace AND
            NOT condeferrable
    LOOP
        EXECUTE format(
            'ALTER TABLE %s ALTER CONSTRAINT %I DEFERRABLE INITIALLY IMMEDIATE',
            record.table_name,
            record.conname
        );
    END LOOP;
END;
$$;
